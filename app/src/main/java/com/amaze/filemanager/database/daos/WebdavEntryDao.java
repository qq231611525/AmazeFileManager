package com.amaze.filemanager.database.daos;

import static com.amaze.filemanager.database.UtilitiesDatabase.COLUMN_NAME;
import static com.amaze.filemanager.database.UtilitiesDatabase.COLUMN_PATH;
import static com.amaze.filemanager.database.UtilitiesDatabase.TABLE_WEBDAV;

import java.util.List;

import com.amaze.filemanager.database.models.utilities.WebdavEntry;

import androidx.room.Dao;
import androidx.room.Insert;
import androidx.room.OnConflictStrategy;
import androidx.room.Query;
import androidx.room.Update;

import io.reactivex.Completable;
import io.reactivex.Single;

/**
 * {@link Dao} interface definition for {@link WebdavEntry}. Concrete class is generated by Room
 * during build.
 *
 * @see Dao
 * @see WebdavEntry
 * @see com.amaze.filemanager.database.UtilitiesDatabase
 */
@Dao
public interface WebdavEntryDao {

  @Insert(onConflict = OnConflictStrategy.IGNORE)
  Completable insert(WebdavEntry instance);

  @Update
  Completable update(WebdavEntry instance);

  @Query("SELECT * FROM " + TABLE_WEBDAV)
  Single<List<WebdavEntry>> list();

  @Query(
      "SELECT * FROM "
          + TABLE_WEBDAV
          + " WHERE "
          + COLUMN_NAME
          + " = :name AND "
          + COLUMN_PATH
          + " = :path")
  Single<List<WebdavEntry>> findByNameAndPath(String name, String path);

  @Query("DELETE FROM " + TABLE_WEBDAV + " WHERE " + COLUMN_NAME + " = :name AND " + COLUMN_PATH + " = :path")
  Completable deleteByNameAndPath(String name, String path);
}
